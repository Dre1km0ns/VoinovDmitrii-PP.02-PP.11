\set ON_ERROR_STOP on
SET client_min_messages = warning;

DROP SCHEMA IF EXISTS cafe CASCADE;
CREATE SCHEMA cafe;
COMMENT ON SCHEMA cafe IS 'Система бронирования столиков в кафе (ПП.02)';
SET search_path = cafe;

-- ---------- Роли ----------
CREATE TABLE roles (
    id    smallint    GENERATED BY DEFAULT AS IDENTITY,
    name  varchar(30) NOT NULL,
    CONSTRAINT pk_roles PRIMARY KEY (id),
    CONSTRAINT uq_roles_name UNIQUE (name),
    CONSTRAINT ck_roles_name CHECK (name IN ('администратор', 'менеджер', 'гость'))
);
COMMENT ON TABLE roles IS 'Роли пользователей системы';

-- ---------- Пользователи ----------
CREATE TABLE users (
    id             integer      GENERATED BY DEFAULT AS IDENTITY,
    login          varchar(50)  NOT NULL,
    password_hash  varchar(255) NOT NULL,
    full_name      varchar(100) NOT NULL,
    role_id        smallint     NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_login UNIQUE (login),
    CONSTRAINT ck_users_login CHECK (login ~ '^[a-z0-9_.]{3,50}$'),
    CONSTRAINT ck_users_password_hash CHECK (password_hash <> ''),
    CONSTRAINT ck_users_full_name CHECK (btrim(full_name) <> ''),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles (id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);
COMMENT ON TABLE users IS 'Учётные записи сотрудников и служебная запись сайта';
COMMENT ON COLUMN users.password_hash IS 'Только хеш пароля; «!» — вход запрещён (хеширование — этап 7)';

-- ---------- Гости ----------
CREATE TABLE guests (
    id         integer      GENERATED BY DEFAULT AS IDENTITY,
    full_name  varchar(100) NOT NULL,
    phone      varchar(12)  NOT NULL,
    email      varchar(100),
    CONSTRAINT pk_guests PRIMARY KEY (id),
    CONSTRAINT uq_guests_phone UNIQUE (phone),
    CONSTRAINT ck_guests_full_name CHECK (btrim(full_name) <> ''),
    CONSTRAINT ck_guests_phone CHECK (phone ~ '^\+7[0-9]{10}$'),
    CONSTRAINT ck_guests_email CHECK (email IS NULL OR email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')
);
COMMENT ON TABLE guests IS 'Посетители кафе, на которых оформляются брони';

-- ---------- Залы ----------
CREATE TABLE halls (
    id           smallint    GENERATED BY DEFAULT AS IDENTITY,
    name         varchar(50) NOT NULL,
    description  text,
    CONSTRAINT pk_halls PRIMARY KEY (id),
    CONSTRAINT uq_halls_name UNIQUE (name),
    CONSTRAINT ck_halls_name CHECK (btrim(name) <> '')
);
COMMENT ON TABLE halls IS 'Залы кафе';

-- ---------- Столики ----------
CREATE TABLE cafe_tables (
    id        integer  GENERATED BY DEFAULT AS IDENTITY,
    hall_id   smallint NOT NULL,
    number    smallint NOT NULL,
    capacity  smallint NOT NULL,
    CONSTRAINT pk_cafe_tables PRIMARY KEY (id),
    CONSTRAINT uq_cafe_tables_hall_number UNIQUE (hall_id, number),
    CONSTRAINT ck_cafe_tables_number CHECK (number > 0),
    CONSTRAINT ck_cafe_tables_capacity CHECK (capacity BETWEEN 1 AND 20),
    CONSTRAINT fk_cafe_tables_hall FOREIGN KEY (hall_id) REFERENCES halls (id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);
COMMENT ON TABLE cafe_tables IS 'Столики; номер уникален в пределах зала';

-- ---------- Брони ----------
CREATE TABLE bookings (
    id            bigint      GENERATED BY DEFAULT AS IDENTITY,
    guest_id      integer     NOT NULL,
    table_id      integer     NOT NULL,
    user_id       integer     NOT NULL,
    booking_date  date        NOT NULL,
    time_start    time(0)     NOT NULL,
    time_end      time(0)     NOT NULL,
    guests_count  smallint    NOT NULL,
    status        varchar(10) NOT NULL DEFAULT 'new',
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_bookings PRIMARY KEY (id),
    CONSTRAINT ck_bookings_time CHECK (time_end > time_start),
    CONSTRAINT ck_bookings_guests_count CHECK (guests_count BETWEEN 1 AND 50),
    CONSTRAINT ck_bookings_status CHECK (status IN ('new', 'confirmed', 'rejected', 'cancelled')),
    CONSTRAINT fk_bookings_guest FOREIGN KEY (guest_id) REFERENCES guests (id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_bookings_table FOREIGN KEY (table_id) REFERENCES cafe_tables (id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_bookings_user FOREIGN KEY (user_id) REFERENCES users (id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);
COMMENT ON TABLE bookings IS 'Брони столиков';
COMMENT ON COLUMN bookings.status IS 'new — новая, confirmed — подтверждена, rejected — отклонена, cancelled — отменена';

-- ---------- Индексы ----------
-- Внешние ключи (PostgreSQL не создаёт индексы для них автоматически)
CREATE INDEX ix_users_role ON users (role_id);
CREATE INDEX ix_bookings_guest ON bookings (guest_id);
CREATE INDEX ix_bookings_user ON bookings (user_id);
-- Поиск занятых столиков на дату: только активные брони (частичный индекс)
CREATE INDEX ix_bookings_active_table_date ON bookings (table_id, booking_date, time_start)
    WHERE status IN ('new', 'confirmed');
-- Расписание на дату для администратора и менеджера
CREATE INDEX ix_bookings_date_status ON bookings (booking_date, status);
